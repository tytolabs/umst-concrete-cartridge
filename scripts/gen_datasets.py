"""
Generate the four Paper-2 synthetic concrete corpora (seed 42) for umst-concrete-cartridge.

Provenance: imported from the IROS 2026 reproducibility package
`prototype/scripts/gen_paper2_datasets.py` (prototype-2a lineage). D1–D4 are *not* produced here;
they are measured corpora documented in `datasets/PROVENANCE.md`.

Step 1 — mix + strength (this script, ``random.seed(42)``):
  DS_UHPC, DS_SELFHEAL, DS_LUNAR (optional), DS_HIGHSCM — 500 rows each.

Step 2 — laboratory curing columns ``temperature`` (°F) and ``humidity`` (relative humidity, 0–1):
  Added in a second pass after step 1; the bundled CSV SHA-256 values in PROVENANCE pin the result.
  When writing, existing ``temperature``/``humidity`` cells are preserved row-wise if the destination
  file already exists (so regeneration does not drift the published bundles).

LUNAR: generated by this script but intentionally **not** shipped in the cartridge v0.1 line;
see PROVENANCE.md (removal recorded, CHANGELOG.md).
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import math
import os
import random
import sys
from typing import Iterable, List, Sequence

SEED = 42
BASE_HEADERS = [
    "cement",
    "slag",
    "fly_ash",
    "water",
    "superplasticizer",
    "coarse_agg",
    "fine_agg",
    "age",
    "strength",
    "source",
]
OUT_HEADERS = BASE_HEADERS + ["temperature", "humidity"]

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATASETS_DIR = os.path.join(REPO_ROOT, "datasets")


def clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, v))


def noise(sigma: float) -> float:
    return random.gauss(0, sigma)


def gen_uhpc(n: int = 500) -> List[List[object]]:
    rows: List[List[object]] = []
    for _ in range(n):
        cement = random.uniform(800, 1100)
        water = random.uniform(130, 200)
        w_c = water / cement
        sp = random.uniform(15, 35)
        slag = random.uniform(0, 100)
        fa = random.uniform(100, 250)
        age = random.choice([1, 3, 7, 14, 28, 90, 180, 360])
        f28_base = clamp(250 * (1 - clamp(w_c, 0.15, 0.5) ** 0.7), 80, 200)
        sf_bonus = 0.05 * fa
        age_factor = math.log(max(age, 1) + 1) / math.log(29)
        strength = clamp(f28_base * age_factor + sf_bonus + noise(6), 20, 220)
        rows.append(
            [
                cement,
                slag,
                fa,
                water,
                sp,
                0.0,
                random.uniform(600, 900),
                age,
                round(strength, 2),
                "UHPC",
            ]
        )
    return rows


def gen_selfheal(n: int = 500) -> List[List[object]]:
    rows: List[List[object]] = []
    for _ in range(n):
        cement = random.uniform(300, 450)
        water = random.uniform(160, 220)
        w_c = water / cement
        slag = random.uniform(0, 100)
        fa = random.uniform(0, 80)
        sp = random.uniform(0, 5)
        age = random.choice([7, 14, 28, 56, 90])
        healing_bonus = random.uniform(3, 8)
        f28 = clamp(75 * (1 - w_c ** 0.55) + 0.04 * slag + healing_bonus + noise(4), 20, 65)
        age_f = math.log(age + 1) / math.log(29)
        strength = clamp(f28 * age_f, 10, 70)
        rows.append(
            [
                cement,
                slag,
                fa,
                water,
                sp,
                random.uniform(900, 1100),
                random.uniform(600, 750),
                age,
                round(strength, 2),
                "SELFHEAL",
            ]
        )
    return rows


def gen_lunar(n: int = 500) -> List[List[object]]:
    rows: List[List[object]] = []
    for _ in range(n):
        cement = random.uniform(250, 400)
        water = random.uniform(140, 200)
        w_c = water / cement
        regolith = random.uniform(800, 1200)
        slag = 0.0
        fa = random.uniform(0, 50)
        sp = 0.0
        age = random.choice([3, 7, 14, 28, 56])
        f28 = clamp(45 * (1 - w_c ** 0.6) * (1 - 0.0002 * regolith) + noise(3), 5, 35)
        age_f = math.log(age + 1) / math.log(29)
        strength = clamp(f28 * age_f, 3, 38)
        rows.append(
            [
                cement,
                slag,
                fa,
                water,
                sp,
                regolith,
                random.uniform(400, 600),
                age,
                round(strength, 2),
                "LUNAR",
            ]
        )
    return rows


def gen_highscm(n: int = 500) -> List[List[object]]:
    rows: List[List[object]] = []
    for _ in range(n):
        total_binder = random.uniform(320, 500)
        scm_frac = random.uniform(0.50, 0.80)
        slag_frac = random.uniform(0.30, 0.60)
        fa_frac = clamp(scm_frac - slag_frac, 0, 0.40)
        cement = total_binder * (1 - scm_frac)
        slag = total_binder * slag_frac
        fa = total_binder * fa_frac
        water = random.uniform(150, 200)
        sp = random.uniform(0, 8)
        age = random.choice([7, 14, 28, 56, 90, 180])
        f28 = clamp(
            60 * (cement / total_binder) ** 0.4 * (1 + 0.3 * slag_frac)
            - 15 * (water / total_binder) ** 0.5
            + noise(4),
            20,
            75,
        )
        age_f = math.log(age + 1) / math.log(29)
        late_gain = 1 + 0.15 * (slag_frac) * (math.log(max(age, 28) + 1) - math.log(29))
        strength = clamp(f28 * age_f * late_gain, 10, 80)
        rows.append(
            [
                cement,
                slag,
                fa,
                water,
                sp,
                random.uniform(900, 1100),
                random.uniform(600, 750),
                age,
                round(strength, 2),
                "HIGHSCM",
            ]
        )
    return rows


def generate_all_rows(include_lunar: bool = True) -> dict[str, List[List[object]]]:
    random.seed(SEED)
    out = {
        "dataset_uhpc.csv": gen_uhpc(500),
        "dataset_selfheal.csv": gen_selfheal(500),
    }
    if include_lunar:
        out["dataset_lunar.csv"] = gen_lunar(500)
    out["dataset_highscm.csv"] = gen_highscm(500)
    return out


def _load_env_column(path: str) -> List[tuple[str, str]] | None:
    if not os.path.isfile(path):
        return None
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames or "temperature" not in reader.fieldnames:
            return None
        return [(row["temperature"], row["humidity"]) for row in reader]


def write_dataset(filename: str, rows: Sequence[Sequence[object]], preserve_env: bool) -> None:
    path = os.path.join(DATASETS_DIR, filename)
    env = _load_env_column(path) if preserve_env else None
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(OUT_HEADERS)
        for i, row in enumerate(rows):
            if env is not None and i < len(env):
                t, h = env[i]
                writer.writerow(list(row) + [t, h])
            else:
                writer.writerow(list(row) + ["", ""])
    print(f"  wrote {len(rows)} rows → {path}")


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _row_base_close(gen: Sequence[object], shipped: Sequence[str]) -> bool:
    for i, val in enumerate(gen):
        if i == 8:
            if abs(float(val) - float(shipped[i])) > 0.01:
                return False
        elif i == 9:
            if str(val) != shipped[i]:
                return False
        else:
            if abs(float(val) - float(shipped[i])) > 0.02:
                return False
    return True


def verify_bundled() -> int:
    """Check mix/strength columns match seed-42 regeneration (env columns pinned separately)."""
    expected = generate_all_rows(include_lunar=True)
    del expected["dataset_lunar.csv"]

    failures = 0
    for name, gen_rows in expected.items():
        path = os.path.join(DATASETS_DIR, name)
        with open(path, newline="") as f:
            reader = csv.reader(f)
            hdr = next(reader)
            body = list(reader)
        if len(body) != len(gen_rows):
            print(f"FAIL {name}: row count {len(body)} != {len(gen_rows)}")
            failures += 1
            continue
        bad = sum(1 for g, s in zip(gen_rows, body) if not _row_base_close(g, s))
        if bad:
            print(f"FAIL {name}: {bad} mix/strength rows differ from seed {SEED}")
            failures += 1
        else:
            print(f"OK {name}: mix/strength matches seed {SEED} ({sha256_file(path)})")
    return 1 if failures else 0


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Verify bundled synthetic CSV mix/strength columns against seed 42",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="Rewrite synthetic CSVs (preserves existing temperature/humidity when present)",
    )
    parser.add_argument(
        "--include-lunar",
        action="store_true",
        help="Also write dataset_lunar.csv (not shipped in cartridge v0.1)",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.verify:
        return verify_bundled()

    if not args.write:
        parser.print_help()
        return 2

    print(f"Generating synthetic concrete datasets (seed={SEED})…")
    tables = generate_all_rows(include_lunar=args.include_lunar)
    for name, rows in tables.items():
        if name == "dataset_lunar.csv" and not args.include_lunar:
            continue
        write_dataset(name, rows, preserve_env=True)
    print("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
